#!/usr/bin/env python3
"""Deterministic campaign-manifest builder for /marketing:plan-campaign (BC-12587).

This is the PURE, hermetic computation core that `/marketing:plan-campaign`
delegates to in BOTH its normal and emit runs (ADR-028 D8 / Phase-2 grill DP2-1:
single source of truth, seam = pure-computation vs the IO boundary). Given the
campaign-defining inputs it computes — with NO MCP/network calls and NO real
Linear/SF/EB IDs (those don't exist yet) — and writes to `--out-dir`:

  * manifest.json  — the Step-7 cross-layer index (real IDs = null)
  * issues.json    — the per-issue payloads (container + 8 standard [+ 2 optional]),
                     cross-referenced BY INDEX (blockedBy:[indices]); the command's
                     IO layer resolves indices → real Linear IDs in its second pass
  * brief.md       — the slot-substituted brief skeleton

The command (orchestrator) owns the IO boundary in both runs: the Linear
collision read (re-invoking this builder with --disambiguator on a hit), all MCP
writes (milestone/issues/SF/EB), backfilling real IDs into the live records, the
two-call confirm gate, soft-fail SF, interactive prompts, and EB assignment.
Emit mode = run this builder → write to the sandbox → stop. Normal run = run this
builder → perform the MCP writes from its output → backfill IDs. Because emit
exercises the exact same deterministic code production uses, the per-PR behavioral
eval (BC-12589) is reproducible and needs no API key.

This builder also OWNS the HARD-FAIL validation (Phase-2 grill DP2-2) so the safety
invariants are unit-tested rather than living only in untested command prose:
Step 1b shape regexes, Step 2 canonicality (V/P/O membership + persona↔offer
target_personas), Step 3.2 slug regex, and Step 10.1 labs-gate. On any violation
it prints the canonical ERROR message to stderr and exits non-zero (2).

Stdlib-only per CLAUDE.md § Conventions (reuses the plugin's _shared readers); no
PyYAML, no jsonschema, no network. Same command+helper pattern as
canonicals_bootstrap.py / portfolio_snapshot.py.
"""
